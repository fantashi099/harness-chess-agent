import assert from 'node:assert/strict';
import {gameOutcome, viewerLink, scoreLabel, lastBoardEvent, playbackFrames} from './blog.js';
import {readSelection, benchmarkRun} from './model.js';
assert.equal(gameOutcome({completed:false,outcome:'0-1'}).key,'incomplete');
assert.equal(gameOutcome({outcome:'1-0'}).key,'unknown');
assert.equal(gameOutcome({completed:true,outcome:'*'}).key,'unknown');
assert.equal(gameOutcome({completed:true,outcome:'1/2-1/2'}).label,'Hòa');
assert.equal(scoreLabel([{completed:true,outcome:'1-0'},{completed:true,outcome:'1/2-1/2'},{completed:false,outcome:'0-1'}]),'1,5/3 điểm');
const link = viewerLink('benchmark-report-1500-harness','game_9','decisions-jsonl-25-commit');
assert.deepEqual(readSelection(link.slice(link.indexOf('#'))),{run:'benchmark-report-1500-harness',game:'game_9',event:'decisions-jsonl-25-commit'});
const catalog = {runs:[{id:'historical',policy:'harness',elo:2000},{id:'benchmark',policy:'harness',elo:2000,collection:'benchmark-report'}]};
assert.equal(benchmarkRun(catalog,'harness',2000).id,'benchmark');
assert.equal(viewerLink('run','game_1'),'viewer.html#run=run&game=game_1&event=');
const finalFen = '5k2/3R4/5Np1/2B4p/6B1/3P2P1/1PP1PP1P/3QK2R b K - 0 25';
const recordedFinal = {id:'final',fen:finalFen,type:'commit'};
assert.equal(lastBoardEvent([{id:'candidate',fen:finalFen},recordedFinal,{id:'transport-error'}]), recordedFinal);
const incomplete = {id:'error',fen:finalFen,type:'error'};
assert.equal(lastBoardEvent([recordedFinal,incomplete]), incomplete);
assert.equal(lastBoardEvent([{id:'bad',fen:'invalid'}, {fen:finalFen}]), undefined);
assert.equal(lastBoardEvent([]), undefined);
const start = {id:'start',type:'context',fen:'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1'};
const white = {id:'white',type:'commit',move:'e2e4',fen:'rnbqkbnr/pppppppp/8/8/4P3/8/PPPP1PPP/RNBQKBNR b KQkq - 0 1'};
const black = {id:'black',type:'opponent',move:'d7d5',fen:'rnbqkbnr/ppp1pppp/8/3p4/4P3/8/PPPP1PPP/RNBQKBNR w KQkq - 0 2'};
const stopped = {...black,id:'stopped',type:'error',move:null};
const frames = playbackFrames([start, {...start,id:'analysis',type:'verification'}, white, black, stopped]);
assert.deepEqual(frames.map(frame=>frame.event.id),['start','white','stopped']);
assert.deepEqual(frames.slice(1).map(frame=>frame.move.move),['e2e4','d7d5']);
assert.equal(frames[2].event,stopped);
assert.equal(frames[2].move.beforeFen,white.fen);
assert.deepEqual(playbackFrames([]),[]);
assert.deepEqual(playbackFrames([{id:'none'}]),[]);
assert.deepEqual(playbackFrames([start]),[{event:start}]);
console.log('Blog outcome, scoring, links and playback frames (both colors, repeated analysis, incomplete game) passed.');
